/**
 * Downloads the official, high-resolution FSTest product photos from fstestcorp.com
 * into public/products/fstest/ and writes supabase/update_fstest_images.sql.
 *
 * Run from the project folder:   npm run images:fstest   (or: node scripts/fetch-fstest-images.mjs)
 * Then run supabase/update_fstest_images.sql in Supabase → SQL Editor.
 * Needs Node 18 or newer (built-in fetch).
 */
import fs from "node:fs/promises";
import path from "node:path";

const SITE = "https://www.fstestcorp.com";
const OUT_DIR = path.join("public", "products", "fstest");

// sku → official product page (and a known photo address as a backup)
const products = [
  { sku: "MC31.3165.5", name: "mc200-atp-monitor", page: "/products-detail/id-84.html" },
  { sku: "MC32.3120.5", name: "atp-swab-quicktest", page: "/products-detail/id-85.html" },
  { sku: "MC32.3121.5", name: "instapro-swab", page: "/products-detail/id-186.html", fallback: "/file/upload/gpaa005/2025-09/18/202509181104555620.jpg" },
  { sku: "MC32.4129.5", name: "salmonella-rapid-test", page: "/products-detail/id-76.html", fallback: "/file/upload/gpaa005/2025-10/10/202510101642037489.jpg" },
  { sku: "MC32.4115.5", name: "listeria-rapid-test", page: "/products-detail/id-95.html", fallback: "/file/upload/gpaa005/2025-10/10/202510101638365478.png" },
  { sku: "MC32.4116.5", name: "ecoli-o157-rapid-test", page: "/products-detail/id-98.html" },
  { sku: "MC32.4114.5", name: "staph-aureus-rapid-test", page: "/products-detail/id-97.html" },
  { sku: "FST-COUNT-PLATE", name: "count-plate", page: "/products-detail/id-50.html" },
  // Old placeholder from the first setup that is a real FSTest product: take the first product on its official list page
  { sku: "FST-LIF-002", name: "automatic-colony-counter", listing: "/products/cid-55.html" },
];

// Old placeholders that are only category names (no real product, no photo): hidden from the website
const hidePlaceholders = ["FST-LIF-003", "FST-LIF-004", "FST-LIF-005", "FST-LIF-007"];

const headers = {
  "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126 Safari/537.36",
  "Accept-Language": "en",
};
const IMG_RE = /(?:https?:\/\/www\.fstestcorp\.com)?(\/file\/upload\/gpaa005\/\d{4}-\d{2}\/\d{2}\/\d+\.(?:jpe?g|png|webp))/gi;

/** First product-gallery photo on the page: the first upload image after the "CatNO" line. */
function findPhoto(html) {
  const start = Math.max(0, html.search(/CatNO/i));
  const after = html.slice(start);
  const m = IMG_RE.exec(after);
  IMG_RE.lastIndex = 0;
  return m ? m[1] : null;
}

async function getHtml(url) {
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const res = await fetch(url, { headers });
      if (res.ok) return await res.text();
    } catch { /* retry */ }
    await new Promise((r) => setTimeout(r, 1500 * attempt));
  }
  return null;
}

async function main() {
  await fs.mkdir(OUT_DIR, { recursive: true });
  const sql = [
    "-- Official FSTest product photos (generated by scripts/fetch-fstest-images.mjs)",
    `update products set is_active = false where sku in (${hidePlaceholders.map((s) => `'${s}'`).join(", ")});`,
  ];
  let ok = 0;

  for (const p of products) {
    // Product given by a list page: open its first product
    if (!p.page && p.listing) {
      const list = await getHtml(SITE + p.listing);
      const m = list?.match(/\/products-detail\/id-\d+\.html/);
      if (!m) { console.log(`✗ ${p.sku}: could not open ${SITE + p.listing}`); continue; }
      p.page = m[0];
    }
    const pageUrl = SITE + p.page;
    const html = await getHtml(pageUrl);
    let imgPath = html ? findPhoto(html) : null;
    imgPath ??= p.fallback ?? null;
    if (!imgPath) { console.log(`✗ ${p.sku}: no photo found on ${pageUrl}`); continue; }

    try {
      const res = await fetch(SITE + imgPath, { headers: { ...headers, Referer: pageUrl } });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const buf = Buffer.from(await res.arrayBuffer());
      if (buf.length < 5000) throw new Error("file too small, probably not a photo");
      const ext = path.extname(imgPath).toLowerCase().replace(".jpeg", ".jpg");
      const file = `${p.name}${ext}`;
      await fs.writeFile(path.join(OUT_DIR, file), buf);
      sql.push(`update products set image_url = '/products/fstest/${file}', is_active = true where sku = '${p.sku}';`);
      console.log(`✓ ${p.sku} → public/products/fstest/${file} (${Math.round(buf.length / 1024)} KB)`);
      ok++;
    } catch (e) {
      // Could not save the file: point the product straight at the official photo instead
      sql.push(`update products set image_url = '${SITE}${imgPath}', is_active = true where sku = '${p.sku}';`);
      console.log(`~ ${p.sku}: could not save (${e.message}); using the official photo link directly`);
      ok++;
    }
  }

  await fs.writeFile(path.join("supabase", "update_fstest_images.sql"), sql.join("\n") + "\n");
  console.log(`\n${ok}/${products.length} products now have the official photo. ${hidePlaceholders.length} placeholder entries will be hidden.`);
  console.log("Next: run supabase/update_fstest_images.sql in Supabase → SQL Editor.");
}

main();
